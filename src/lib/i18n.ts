import { useEffect, useState } from 'react'
import type { Language } from '../types/domain'

export const LANGUAGE_STORAGE_KEY = 'kanikan-language'

export const normalizeLanguage = (value: unknown): Language => (value === 'en' ? 'en' : 'id')

export const getStoredLanguage = (fallback: unknown = 'id'): Language => {
  try {
    return normalizeLanguage(window.localStorage.getItem(LANGUAGE_STORAGE_KEY) ?? fallback)
  } catch {
    return normalizeLanguage(fallback)
  }
}

export const hasStoredLanguage = () => {
  try {
    return window.localStorage.getItem(LANGUAGE_STORAGE_KEY) === 'id' || window.localStorage.getItem(LANGUAGE_STORAGE_KEY) === 'en'
  } catch {
    return false
  }
}

export const setStoredLanguage = (language: Language) => {
  window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language)
  window.dispatchEvent(new CustomEvent('kanikan-language-change', { detail: language }))
}

export const useAppLanguage = (preferred?: unknown): Language => {
  const [language, setLanguage] = useState<Language>(() => getStoredLanguage(preferred))

  useEffect(() => {
    if (!hasStoredLanguage() && preferred) {
      setLanguage(normalizeLanguage(preferred))
    }
  }, [preferred])

  useEffect(() => {
    const languageChangeListener = (event: Event) => {
      setLanguage(normalizeLanguage((event as CustomEvent<Language>).detail))
    }
    const storageListener = (event: StorageEvent) => {
      if (event.key === LANGUAGE_STORAGE_KEY) {
        setLanguage(normalizeLanguage(event.newValue))
      }
    }
    window.addEventListener('kanikan-language-change', languageChangeListener)
    window.addEventListener('storage', storageListener)
    return () => {
      window.removeEventListener('kanikan-language-change', languageChangeListener)
      window.removeEventListener('storage', storageListener)
    }
  }, [])

  return language
}

